    """返回内置红队样本。

    当前阶段保持本地、可审计、可版本化；样本均为合成数据，不包含真实用户聊天。
    """

    cases = (
        list(DEFAULT_REDTEAM_CASES)
        + _expanded_crisis_cases()
        + build_rag_acceptance_cases()
        + build_hierarchical_hard_cases()
        + build_route_acceptance_cases()
    )
    return [case.model_copy(deep=True) for case in cases]
